#!/bin/bash
#
# Pin the backend's dependencies to the versions a working install runs.
#
# Why (2026-09-24): requirements.txt is unpinned. With langgraph-checkpoint-postgres 3.0.5 and psycopg 3.3.6,
# reading an older-format checkpoint raises "operator does not exist:
# text = bytea", and httpx 0.28 removed TestClient(app=) — so a venv rebuild
# would break chat on old threads and half the test suite. This freezes the
# known-good set; backend/start.sh installs with `-c constraints.txt` when
# the file exists.
#
# Run it on a known-good install, from the repo:
#   bash scripts/pin_requirements.sh              # writes backend/constraints.txt
#   bash scripts/pin_requirements.sh /tmp/c.txt   # somewhere else
# then review the diff and commit backend/constraints.txt.
#
# Editable installs (-e), local paths and direct URL references (`pkg @ …`)
# are left out: they are not versions another machine can install, and
# pip refuses editables in a constraints file.

# filter_freeze: `pip freeze` on stdin → constraint lines on stdout; what it
# drops goes to stderr. Pure, so scripts/test_pin_requirements.sh tests it.
filter_freeze() {
    local line
    while IFS= read -r line || [ -n "$line" ]; do
        line="${line%$'\r'}"
        case "$line" in
            ""|"#"*) continue ;;
            -e\ *|--editable*|-e*) echo "skipped (editable): $line" >&2; continue ;;
            *" @ "*) echo "skipped (direct reference): $line" >&2; continue ;;
            file:*|/*|./*|../*) echo "skipped (local path): $line" >&2; continue ;;
        esac
        case "$line" in
            *==*) echo "$line" ;;
            *) echo "skipped (unpinned): $line" >&2 ;;
        esac
    done
}

# psycopg_pair_problem: constraint lines on stdin -> why their psycopg pins
# would break a fresh Mac, or nothing. psycopg-binary (its own libpq) must be
# pinned, at psycopg's version: postgresql@16 is keg-only, so pure-python
# psycopg finds no libpq there and the backend dies at import.
psycopg_pair_problem() {
    local lines p b
    lines="$(cat)"
    p="$(printf '%s\n' "$lines" | awk -F'==' '!f && tolower($1) == "psycopg" { print $2; f = 1 }')"
    [ -n "$p" ] || return 0
    b="$(printf '%s\n' "$lines" | awk -F'==' '!f && (tolower($1) == "psycopg-binary" || tolower($1) == "psycopg_binary") { print $2; f = 1 }')"
    if [ -z "$b" ]; then
        echo "psycopg==$p is pinned without psycopg-binary (this venv lacks it: pip install -r requirements.txt -c constraints.txt first)"
    elif [ "$b" != "$p" ]; then
        echo "psycopg-binary==$b does not match psycopg==$p"
    fi
}

# Sourced by the tests: stop here, run nothing.
[ -n "${PIN_REQUIREMENTS_LIB_ONLY:-}" ] && return 0

set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
BACKEND="${EDWARD_BACKEND_DIR:-$HERE/../backend}"
VENV_PY="${EDWARD_VENV_PYTHON:-$BACKEND/.venv/bin/python}"
OUT="${1:-$BACKEND/constraints.txt}"

if [ ! -x "$VENV_PY" ]; then
    echo "No venv python at $VENV_PY — run setup.sh first (or set EDWARD_VENV_PYTHON)." >&2
    exit 1
fi

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
"$VENV_PY" -m pip freeze | filter_freeze > "$TMP"

if [ ! -s "$TMP" ]; then
    echo "pip freeze produced no pinned lines — not writing $OUT" >&2
    exit 1
fi
WHY="$(psycopg_pair_problem < "$TMP")"
if [ -n "$WHY" ]; then
    echo "$WHY — not writing $OUT" >&2
    exit 1
fi

{
    echo "# Generated by scripts/pin_requirements.sh on $(date -u +%Y-%m-%dT%H:%MZ) from $("$VENV_PY" --version 2>&1)."
    echo "# A known-good set; setup.sh and backend/start.sh install with -c constraints.txt."
    echo "# Regenerate after a deliberate, tested upgrade; never hand-edit a version down."
    cat "$TMP"
} > "$OUT"

echo "Wrote $(grep -vc '^#' "$OUT") pinned packages to $OUT"
for pkg in langgraph langgraph-checkpoint-postgres psycopg psycopg-binary httpx fastapi starlette; do
    grep -i "^${pkg}==" "$OUT" || true
done
